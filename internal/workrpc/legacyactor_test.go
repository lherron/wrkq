// ─── gap2 seeding helpers ─────────────────────────────────────────────────────

// g2SeedActor inserts an actor row directly into dbPath (slug must be unique).
// The uuid and friendly id are auto-generated by DB triggers/defaults.
// Returns the actor's UUID.
func g2SeedActor(t *testing.T, dbPath, slug, displayName, role string) string {
	t.Helper()
	database, err := db.Open(dbPath)
	if err != nil {
		t.Fatalf("g2SeedActor: db.Open: %v", err)
	}
	defer func() { _ = database.Close() }()

	if _, err := database.Exec(
		`INSERT INTO actors (id, slug, display_name, role) VALUES ('', ?, ?, ?)`,
		slug, displayName, role,
	); err != nil {
		t.Fatalf("g2SeedActor %q: %v", slug, err)
	}
	var uuid string
	if err := database.QueryRow("SELECT uuid FROM actors WHERE slug = ?", slug).Scan(&uuid); err != nil {
		t.Fatalf("g2SeedActor: fetch uuid for %q: %v", slug, err)
	}
	return uuid
}

// g2ActorMeta reads the raw meta text from the DB for the given actor UUID.
// Returns "" when meta is NULL.
func g2ActorMeta(t *testing.T, dbPath, uuid string) string {
	t.Helper()
	database, err := db.Open(dbPath)
	if err != nil {
		t.Fatalf("g2ActorMeta: db.Open: %v", err)
	}
	defer func() { _ = database.Close() }()

	var meta *string
	if err := database.QueryRow("SELECT meta FROM actors WHERE uuid = ?", uuid).Scan(&meta); err != nil {
		t.Fatalf("g2ActorMeta %q: %v", uuid, err)
	}
	if meta == nil {
		return ""
	}
	return *meta
}

// g2CountActorEvents counts event_log rows with the given event_type and actor UUID.
// Pass "" for actorUUID to count all events of that type.
func g2CountActorEvents(t *testing.T, dbPath, eventType, actorUUID string) int {
	t.Helper()
	database, err := db.Open(dbPath)
	if err != nil {
		t.Fatalf("g2CountActorEvents: db.Open: %v", err)
	}
	defer func() { _ = database.Close() }()

	var count int
	var qErr error
	if actorUUID != "" {
		qErr = database.QueryRow(
			"SELECT COUNT(*) FROM event_log WHERE event_type = ? AND resource_uuid = ?",
			eventType, actorUUID,
		).Scan(&count)
	} else {
		qErr = database.QueryRow(
			"SELECT COUNT(*) FROM event_log WHERE event_type = ?", eventType,
		).Scan(&count)
	}
	if qErr != nil {
		t.Fatalf("g2CountActorEvents(%s): %v", eventType, qErr)
	}
	return count
}

