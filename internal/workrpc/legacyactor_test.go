func TestOrdinaryTaskCreate_SucceedsWithNoActorRowForPrincipal(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping subprocess in short mode")
	}
	dbPath := migratedDB(t)

	// No actor row is seeded for a hypothetical external principal.
	// The RPC server uses its DefaultActor (wrkq-system) for DB attribution;
	// principal_ref is a free-text field with no FK — task creates must succeed.
	frames := p2Run(t, dbPath,
		mkRPC("tc1", "wrkq.task.create", map[string]any{
			"title": "No Actor Row Task",
			"kind":  "task",
		}),
	)
	result := p2ResultOrFail(t, frames[1], "wrkq.task.create without actor row for principal")
	p2AssertStr(t, result, "uuid")
	p2AssertStr(t, result, "id")
}
