// TestLegacyActorMethods_PresentOnBothEntrypoints verifies that
// wrkq.admin.legacyActor.list, .create, and .update are registered and
// reachable on BOTH wrkq rpc --stdio AND wrkf rpc --stdio.
//
// Each method is called with empty params; an implemented method returns
// WRKQ_VALIDATION (param validation), not "method not found".
//
// RED: all three methods are unregistered → each call returns "method not found"
// → g1IsMethodNotFound returns true → test fails.
func TestLegacyActorMethods_PresentOnBothEntrypoints(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping subprocess in short mode")
	}

	methods := []string{
		"wrkq.admin.legacyActor.list",
		"wrkq.admin.legacyActor.create",
		"wrkq.admin.legacyActor.update",
	}
	entrypoints := []string{"wrkq", "wrkf"}

	for _, ep := range entrypoints {
		ep := ep
		t.Run(ep, func(t *testing.T) {
			dbPath := migratedDB(t)
			for _, method := range methods {
				method := method
				t.Run(method, func(t *testing.T) {
					// Call with empty params — registered method returns WRKQ_VALIDATION,
					// unregistered returns "method not found".
					frames := g1Run(t, ep, dbPath,
						mkRPC("m1", method, map[string]any{}),
					)
					if g1IsMethodNotFound(frames[1]) {
						t.Errorf("entrypoint %s: method %q is not registered "+
							"(got 'method not found'); must be present on both "+
							"wrkq and wrkf entrypoints", ep, method)
					}
				})
			}
		})
	}
}

